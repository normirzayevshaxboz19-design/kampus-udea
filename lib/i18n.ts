export function tr(lang: Lang, text: string): string {
  if (lang === "uz") return text;
  return D[text]?.[lang] ?? text;
}

export function tpl(lang: Lang, text: string, vars: Record<string, string | number>): string {
  return tr(lang, text).replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}

export function makeT(lang: Lang) {
  return (text: string) => tr(lang, text);
}
